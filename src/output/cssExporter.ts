import { AnalyzePageResponseData } from '../types/index.ts';

export function exportCssVariables(data: AnalyzePageResponseData): string {
  const colorSys = data.colorSystem;
  const typoSys = data.typographySystem;
  const shapeSys = data.shapeSystem;
  const layoutSys = data.layoutSystem;

  const lines: string[] = [];
  lines.push('/* Auto-generated by UI/UX Helper Extension */');
  lines.push(':root {');

  const declaredVars = new Set<string>();
  function addVar(name: string, value: string) {
    if (!declaredVars.has(name) && value) {
      declaredVars.add(name);
      lines.push(`  ${name}: ${value};`);
    }
  }

  // Colors
  if (colorSys) {
    if (colorSys.roles?.pageBackground) addVar('--color-bg-page', (colorSys.roles.pageBackground as any).color?.hex || (colorSys.roles.pageBackground as any).hex || '#ffffff');
    if (colorSys.roles?.surfaceBackground) addVar('--color-bg-surface', (colorSys.roles.surfaceBackground as any).color?.hex || (colorSys.roles.surfaceBackground as any).hex || '#ffffff');
    if (colorSys.roles?.primaryText) addVar('--color-text-primary', (colorSys.roles.primaryText as any).color?.hex || (colorSys.roles.primaryText as any).hex || '#000000');
    if (colorSys.roles?.secondaryText) addVar('--color-text-secondary', (colorSys.roles.secondaryText as any).color?.hex || (colorSys.roles.secondaryText as any).hex || '#666666');
    if (colorSys.roles?.border) addVar('--color-border', (colorSys.roles.border as any).color?.hex || (colorSys.roles.border as any).hex || '#e2e8f0');
    if (colorSys.roles?.primaryAccent) addVar('--color-primary-accent', (colorSys.roles.primaryAccent as any).color?.hex || (colorSys.roles.primaryAccent as any).hex || '#3b82f6');
    if (colorSys.roles?.interactiveCTA) addVar('--color-interactive-cta', (colorSys.roles.interactiveCTA as any).color?.hex || (colorSys.roles.interactiveCTA as any).hex || '#3b82f6');

    if (Array.isArray(colorSys.tokens)) {
      const uniqueHexes = new Set<string>();
      let pIdx = 1;
      colorSys.tokens.forEach((t: any) => {
        const hex = t.color?.hex || t.hex || '#000000';
        if (!uniqueHexes.has(hex.toLowerCase())) {
          uniqueHexes.add(hex.toLowerCase());
          addVar(`--color-palette-${pIdx++}`, hex);
        }
      });
    }
  }

  // Typography
  if (typoSys) {
    if (Array.isArray(typoSys.fontFamilies)) {
      typoSys.fontFamilies.forEach((f: any, idx) => {
        addVar(`--font-family-${idx + 1}`, f.name || f.primary);
      });
    }
    if (typoSys.hierarchy?.h1) addVar('--font-size-h1', `${typoSys.hierarchy.h1.fontSizePx}px`);
    if (typoSys.hierarchy?.body) addVar('--font-size-body', `${typoSys.hierarchy.body.fontSizePx}px`);
  }

  // Spacing Scale
  addVar('--spacing-xs', '4px');
  addVar('--spacing-sm', '8px');
  addVar('--spacing-md', '16px');
  addVar('--spacing-lg', '24px');
  addVar('--spacing-xl', '32px');
  addVar('--spacing-2xl', '48px');
  addVar('--spacing-3xl', '64px');

  if (layoutSys && Array.isArray(layoutSys.spacingScale)) {
    const uniqueSp = Array.from(new Set(layoutSys.spacingScale.map((s) => Math.round(s.valuePx)))).sort((a, b) => a - b);
    uniqueSp.forEach((sp) => {
      if (sp > 0) addVar(`--spacing-${sp}`, `${sp}px`);
    });
  }

  // Radius & Shadows
  if (shapeSys) {
    if (Array.isArray(shapeSys.radiusScale)) {
      shapeSys.radiusScale.forEach((r) => {
        addVar(`--radius-${Math.round(r.valuePx)}`, `${Math.round(r.valuePx)}px`);
      });
    } else if (Array.isArray((shapeSys as any).radiusTokens)) {
      (shapeSys as any).radiusTokens.forEach((r: any) => {
        addVar(`--radius-${Math.round(r.valuePx)}`, `${Math.round(r.valuePx)}px`);
      });
    }
    if (Array.isArray(shapeSys.shadowTokens)) {
      shapeSys.shadowTokens.forEach((s, idx) => {
        addVar(`--shadow-${idx + 1}`, s.rawString);
      });
    }
  }

  lines.push('}');
  lines.push('');

  // Reusable utility classes
  lines.push('/* Reusable Design Utilities */');
  lines.push('.u-page-bg { background-color: var(--color-bg-page, #ffffff); }');
  lines.push('.u-surface-bg { background-color: var(--color-bg-surface, #f8fafc); }');
  lines.push('.u-text-primary { color: var(--color-text-primary, #0f172a); }');
  lines.push('.u-text-secondary { color: var(--color-text-secondary, #64748b); }');
  lines.push('.u-btn-primary { background-color: var(--color-interactive-cta, #3b82f6); color: white; border: none; border-radius: var(--radius-8, 8px); }');

  return lines.join('\n');
}
